String channelIconLabel(String name) {
  var value = name.startsWith('Fa') ? name.substring(2) : name;
  if (value.endsWith('Icon')) {
    value = value.substring(0, value.length - 4);
  }
  value = value.replaceAllMapped(
      RegExp(r'([a-z0-9])([A-Z])'), (match) => '${match[1]} ${match[2]}');
  value = value.replaceAllMapped(
      RegExp(r'([A-Z])([A-Z][a-z])'), (match) => '${match[1]} ${match[2]}');
  if (value.isEmpty) return name;
  return value[0].toUpperCase() + value.substring(1);
}
