// Generates src/lib/channel-icons.ts from Heroicons 24/solid (MIT).
// Source: https://www.npmjs.com/package/heroicons
import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import os from "node:os";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir =
  process.env.HEROICONS_DIR ??
  join(os.tmpdir(), "heroicons-pkg", "extract", "package", "24", "solid");

function pascal(name) {
  return name
    .split("-")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("");
}

const icons = {};
for (const file of (await readdir(dir)).filter((name) => name.endsWith(".svg"))) {
  const svg = await readFile(join(dir, file), "utf8");
  const paths = [];
  for (const match of svg.matchAll(/<path\b([^>]*)\/?>/g)) {
    const attrs = match[1];
    const d = attrs.match(/\bd="([^"]+)"/)?.[1];
    if (!d) continue;
    const fillRule = attrs.match(/fill-rule="([^"]+)"/)?.[1];
    const clipRule = attrs.match(/clip-rule="([^"]+)"/)?.[1];
    paths.push({ d, fillRule, clipRule });
  }
  const name = pascal(file.replace(/\.svg$/, ""));
  icons[`${name}Icon`] = paths;
  icons[name] = paths;
}

const content = `// Generated by scripts/build-channel-icons.mjs from Heroicons 2.2.0 (MIT).\n// Do not edit by hand.\nexport interface ChannelIconPath {\n  d: string;\n  fillRule?: "evenodd" | "nonzero";\n  clipRule?: "evenodd" | "nonzero";\n}\n\nexport const channelIcons: Record<string, ChannelIconPath[]> = ${JSON.stringify(icons)};\n`;
await writeFile(join(root, "src", "lib", "channel-icons.ts"), content);
console.log(`Wrote ${Object.keys(icons).length} channel icons.`);
