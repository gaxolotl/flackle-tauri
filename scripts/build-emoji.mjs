// Regenerates the bundled Twemoji set and src/lib/emoji-data.ts.
//
// Sources:
//   - https://github.com/jdecked/twemoji/releases/tag/v15.1.0 (assets/svg)
//   - https://cdn.jsdelivr.net/npm/emoji-datasource@15.1.2/emoji.json
//
// Usage:
//   TWEMOJI_DIR=/path/to/twemoji/assets/svg EMOJI_JSON=/path/to/emoji.json node scripts/build-emoji.mjs
// Defaults point at the temporary extraction paths used during development.
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import os from "node:os";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outDir = join(root, "public", "emoji");
const sourceDir =
  process.env.TWEMOJI_DIR ??
  join(os.tmpdir(), "twemoji-extract", "twemoji-15.1.0", "assets", "svg");
const jsonPath = process.env.EMOJI_JSON ?? join(os.tmpdir(), "emoji.json");

if (!existsSync(sourceDir)) {
  console.error(`Twemoji SVG directory not found: ${sourceDir}`);
  process.exit(1);
}
if (!existsSync(jsonPath)) {
  console.error(`emoji.json not found: ${jsonPath}`);
  process.exit(1);
}

const order = [
  ["Smileys & Emotion", "smileys"],
  ["People & Body", "people"],
  ["Animals & Nature", "nature"],
  ["Food & Drink", "food"],
  ["Travel & Places", "travel"],
  ["Activities", "activities"],
  ["Objects", "objects"],
  ["Symbols", "symbols"],
  ["Flags", "flags"],
];

const data = JSON.parse(await readFile(jsonPath, "utf8"));
const files = new Set(
  (await import("node:fs/promises").then((fs) => fs.readdir(sourceDir))).filter((name) =>
    name.endsWith(".svg"),
  ),
);

function charFromUnified(unified) {
  return unified
    .split("-")
    .map((part) => String.fromCodePoint(Number.parseInt(part, 16)))
    .join("");
}

function candidates(entry) {
  const unified = entry.unified.toLowerCase();
  const parts = unified.split("-").map((part) => part.replace(/^0+/, "") || "0");
  const stripped = parts.filter((part) => part !== "fe0f");
  const noZeroStripped = entry.unified
    .toLowerCase()
    .split("-")
    .map((part) => part.replace(/^0+/, "") || "0");
  return [
    unified,
    entry.non_qualified?.toLowerCase(),
    parts.join("-"),
    stripped.join("-"),
    noZeroStripped.join("-"),
    noZeroStripped.filter((part) => part !== "fe0f").join("-"),
  ].filter(Boolean);
}

function findFile(entry) {
  for (const candidate of new Set(candidates(entry))) {
    const name = `${candidate}.svg`;
    if (files.has(name)) return name;
  }
  return null;
}

await mkdir(outDir, { recursive: true });

const categories = [];
const seen = new Set();
let copied = 0;
let missing = 0;

for (const [categoryName, id] of order) {
  const entries = [];
  const source = data
    .filter((entry) => entry.category === categoryName)
    .sort((a, b) => (a.sort_order ?? 0) - (b.sort_order ?? 0));
  for (const entry of source) {
    const char = charFromUnified(entry.unified);
    if (seen.has(char)) continue;
    seen.add(char);
    const file = findFile(entry);
    if (!file) {
      missing += 1;
      continue;
    }
    await copyFile(join(sourceDir, file), join(outDir, file));
    copied += 1;
    entries.push({
      char,
      name: String(entry.name ?? entry.short_name ?? "").toLowerCase(),
      keywords: [entry.short_name, ...(entry.short_names ?? []), ...(entry.keywords ?? [])]
        .filter(Boolean)
        .join(" "),
      file,
    });
  }
  categories.push({ id, label: categoryName, entries });
}

const content = `// Generated by scripts/build-emoji.mjs. Do not edit by hand.\nexport interface EmojiEntry {\n  char: string;\n  name: string;\n  keywords: string;\n  file: string;\n}\n\nexport interface EmojiCategory {\n  id: string;\n  label: string;\n  entries: EmojiEntry[];\n}\n\nexport const emojiCategories: EmojiCategory[] = ${JSON.stringify(categories)};\n`;

await writeFile(join(root, "src", "lib", "emoji-data.ts"), content);

console.log(`Bundled ${copied} emoji in ${categories.length} categories.`);
if (missing) console.warn(`${missing} emoji had no Twemoji file and were skipped.`);
